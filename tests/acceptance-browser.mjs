import { createRequire } from "node:module";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const { chromium } = createRequire(import.meta.url)("playwright");
const browser = await chromium.launch({ headless: true, executablePath: process.env.ARCHI_BROWSER_EXECUTABLE || undefined });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on("pageerror", (e) => errors.push(e.message));
  await page.goto((process.env.ARCHI_URL ?? "http://127.0.0.1:4173") + "/?view=acceptance");
  const cases = page.getByLabel("Scenario case");
  await cases.waitFor();
  assert.equal(await cases.locator("option").count(), 14);
  await cases.selectOption("T3/qa");
  assert.match(await page.locator(".expectation-table").innerText(), /matching · progressing · information/);
  await cases.selectOption("T4/qa");
  assert.match(await page.locator(".runtime-detail").innerText(), /ProgressDeadlineExceeded/);
  await page.screenshot({ path: "artifacts/acceptance-scenario.png", fullPage: true });
  await cases.selectOption("T5/qa");
  await page.getByRole("button", { name: "Compare captures", exact: true }).click();
  await page.getByLabel("Before capture").selectOption("T4/qa");
  assert.match(await page.locator(".capture-comparison").innerText(), /reported-failure/);
  assert.match(await page.locator(".capture-comparison").innerText(), /information/);
  await page.screenshot({ path: "artifacts/acceptance-comparison.png", fullPage: true });
  await cases.selectOption("T6/production");
  assert.ok((await page.getByLabel("Before capture").locator("option").allTextContents()).every((s) => s.includes("production")));
  await page.getByRole("button", { name: "How to use" }).click();
  const guide = page.getByRole("dialog", { name: "From configuration to evidence." });
  await guide.waitFor();
  await guide.getByRole("button", { name: "Next", exact: true }).click();
  assert.match(await guide.innerText(), /Keep your existing Helm chart/);
  await guide.getByRole("button", { name: "Play walkthrough", exact: true }).click();
  assert.equal(await guide.getByRole("button", { name: "Pause", exact: true }).getAttribute("aria-pressed"), "true");
  await guide.getByRole("button", { name: "Pause", exact: true }).click();
  await page.screenshot({ path: "artifacts/usage-guide.png", animations: "disabled" });
  await page.keyboard.press("Escape");
  assert.equal(await guide.count(), 0);
  assert.match(await page.locator(":focus").innerText(), /How to use/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "How to use" }).click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: "artifacts/usage-guide-mobile.png", animations: "disabled" });
  await page.keyboard.press("Escape");
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export bundle", exact: true }).click();
  const exported = JSON.parse(await readFile(await (await download).path(), "utf8"));
  assert.equal(exported.cases.length, 14);
  await page.getByLabel("Open acceptance bundle").setInputFiles({ name: "bad.json", mimeType: "application/json", buffer: Buffer.from('{}') });
  await page.getByRole("alert").waitFor();
  assert.equal(await cases.count(), 0);
  await page.getByLabel("Open acceptance bundle").setInputFiles("artifacts/acceptance/bundle.json");
  await cases.waitFor();
  assert.deepEqual(errors, []);
  console.log("Acceptance browser passed: phases, environment isolation, comparison, import/export, animated guide, focus and mobile");
} finally { await browser.close(); }
